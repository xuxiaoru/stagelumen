#!/usr/bin/env node
/**
 * Build-time blog generator.
 *
 * Reads content/blog/*.md (the Decap CMS "blog" collection) and produces:
 *   1. content/blog/<slug>.html  — a static article page, SEO-friendly
 *   2. data/posts.json           — a machine-readable index
 *   3. news.html                 — the card grid, injected between POSTS markers
 *
 * Cloudflare Pages build command:
 *   node build/inject-settings.js && node build/build-blog.js
 *
 * Constraints that shaped this file:
 *   - Zero dependencies. Pages has no install step, so no markdown package.
 *   - Never break the site. If content/blog is empty or a post is malformed,
 *     we log and continue; news.html keeps whatever it had (see KEEP_GRID).
 *   - Hand-written HTML is always overwritten: the .md file is the single
 *     source of truth, because that is what the CMS edits.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const BLOG_DIR = path.join(ROOT, 'content', 'blog');
const DATA_DIR = path.join(ROOT, 'data');
const NEWS_FILE = path.join(ROOT, 'news.html');
const SITEMAP_FILE = path.join(ROOT, 'sitemap.xml');
const SITE = 'https://stagelumen.pages.dev';

const GENERATED = 'generated by build/build-blog.js';

/**
 * Article pages used to link style.css with no version, so a cached copy never
 * picked up CSS fixes. Read the version the hand-written pages use instead —
 * one place to bump, and the two cannot drift apart.
 */
function cssVersion() {
  try {
    const idx = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
    const m = idx.match(/style\.css\?v=(\d+)/);
    return m ? '?v=' + m[1] : '';
  } catch (e) {
    return '';
  }
}

/** Card thumbnails cycle through the palette the design already uses. */
const GRADIENTS = [
  'linear-gradient(135deg,#2a1a0a,#1a1a1a)',
  'linear-gradient(135deg,#0a1a2a,#1a1a1a)',
  'linear-gradient(135deg,#1a0a2a,#1a1a1a)',
  'linear-gradient(135deg,#1a2a0a,#1a1a1a)',
  'linear-gradient(135deg,#2a0a1a,#1a1a1a)',
];

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December'];

// ---------------------------------------------------------------- utilities

const escHtml = (s) => String(s == null ? '' : s)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;');

const escAttr = (s) => escHtml(s).replace(/"/g, '&quot;');

function prettyDate(iso) {
  const d = new Date(iso);
  if (isNaN(d.getTime())) return '';
  return MONTHS[d.getUTCMonth()] + ' ' + d.getUTCDate() + ', ' + d.getUTCFullYear();
}

/**
 * Front matter reader for the flat shape the CMS writes:
 * scalars (key: "value") and one level of "- item" lists.
 */
function parseFrontMatter(text) {
  const src = String(text).replace(/^\uFEFF/, '');
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(src);
  if (!m) return { data: {}, body: src };

  const data = {};
  let listKey = null;

  for (const raw of m[1].split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line === '---') continue;

    if (listKey && /^-\s+/.test(line)) {
      data[listKey].push(line.replace(/^-\s+/, '').trim().replace(/^"(.*)"$/, '$1'));
      continue;
    }

    const i = line.indexOf(':');
    if (i < 1) continue;
    const key = line.slice(0, i).trim();
    let val = line.slice(i + 1).trim();
    if (/^"(.*)"$/.test(val)) val = val.slice(1, -1);

    if (val === '') {
      data[key] = [];
      listKey = key;
    } else {
      data[key] = val;
      listKey = null;
    }
  }

  return { data, body: src.slice(m[0].length) };
}

// ------------------------------------------------------------- markdown

function inline(s) {
  let t = escHtml(s);
  t = t.replace(/`([^`]+)`/g, '<code>$1</code>');
  t = t.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  t = t.replace(/(^|[^*])\*([^*]+)\*/g, '$1<em>$2</em>');
  t = t.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '<a href="$2">$1</a>');
  return t;
}

function splitRow(line) {
  return line.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
}

function renderTable(head, rows) {
  const th = head.map((c) => '<th>' + inline(c) + '</th>').join('');
  const tb = rows
    .map((r) => '<tr>' + r.map((c) => '<td>' + inline(c) + '</td>').join('') + '</tr>')
    .join('\n          ');
  return '<table>\n        <thead>\n          <tr>' + th + '</tr>\n        </thead>\n' +
    '        <tbody>\n          ' + tb + '\n        </tbody>\n      </table>';
}

/** Deliberately small subset: what our own content agent actually emits. */
function mdToHtml(md) {
  const lines = String(md).replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let i = 0;
  let inCode = false;
  let codeBuf = [];
  let para = [];
  let listKind = null;
  let items = [];

  const flushPara = () => {
    if (para.length) out.push('<p>' + inline(para.join(' ')) + '</p>');
    para = [];
  };
  const flushList = () => {
    if (listKind && items.length) {
      out.push('<' + listKind + '>' + items.map((x) => '<li>' + inline(x) + '</li>').join('') + '</' + listKind + '>');
    }
    listKind = null;
    items = [];
  };

  while (i < lines.length) {
    const line = lines[i];

    if (/^\s*```/.test(line)) {
      flushPara();
      flushList();
      if (inCode) {
        out.push('<pre><code>' + escHtml(codeBuf.join('\n')) + '</code></pre>');
        codeBuf = [];
      }
      inCode = !inCode;
      i++;
      continue;
    }
    if (inCode) { codeBuf.push(line); i++; continue; }

    if (!line.trim()) { flushPara(); flushList(); i++; continue; }

    // table: header row followed by a |---|---| separator
    if (/^\s*\|/.test(line) && i + 1 < lines.length && /^\s*\|[\s:|-]+\|?\s*$/.test(lines[i + 1])) {
      flushPara();
      flushList();
      const head = splitRow(line);
      i += 2;
      const rows = [];
      while (i < lines.length && /^\s*\|/.test(lines[i])) { rows.push(splitRow(lines[i])); i++; }
      out.push(renderTable(head, rows));
      continue;
    }

    const h = /^(#{1,6})\s+(.*)$/.exec(line);
    if (h) {
      flushPara();
      flushList();
      const lvl = h[1].length;
      // h1 is the post title, already rendered in the page hero — skip it.
      if (lvl > 1) out.push('<h' + lvl + '>' + inline(h[2]) + '</h' + lvl + '>');
      i++;
      continue;
    }

    if (/^\s*(---|\*\*\*)\s*$/.test(line)) { flushPara(); flushList(); out.push('<hr />'); i++; continue; }

    if (/^>\s?/.test(line)) {
      flushPara();
      flushList();
      out.push('<blockquote><p>' + inline(line.replace(/^>\s?/, '')) + '</p></blockquote>');
      i++;
      continue;
    }

    const ul = /^\s*[-*]\s+(.*)$/.exec(line);
    const ol = /^\s*\d+\.\s+(.*)$/.exec(line);
    if (ul || ol) {
      flushPara();
      const kind = ul ? 'ul' : 'ol';
      if (listKind && listKind !== kind) flushList();
      listKind = kind;
      items.push((ul || ol)[1]);
      i++;
      continue;
    }

    para.push(line.trim());
    i++;
  }

  flushPara();
  flushList();
  if (inCode && codeBuf.length) out.push('<pre><code>' + escHtml(codeBuf.join('\n')) + '</code></pre>');

  return out.join('\n\n');
}

