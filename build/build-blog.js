function cardHtml(p, idx, featured) {
  const grad = GRADIENTS[idx % GRADIENTS.length];
  const url = 'content/blog/' + p.slug + '.html';
  const tag = escHtml(p.category || 'Article');
  const heading = featured
    ? '<h2><a href="' + url + '">' + escHtml(p.title) + '</a></h2>'
    : '<h3><a href="' + url + '">' + escHtml(p.title) + '</a></h3>';
  const more = featured ? '\n          <a href="' + url + '" class="link-arrow">Read More →</a>' : '';

  return `      <article class="news-card${featured ? ' featured' : ''}">
        <div class="news-thumb" style="background: ${grad};"></div>
        <div class="news-content">
          <span class="news-tag">${tag}</span>
          ${heading}
          <p class="news-meta">${escHtml(p.datePretty)}</p>
          <p>${escHtml(p.excerpt)}</p>${more}
        </div>
      </article>`;
}

// ------------------------------------------------------------------- main

function main() {
  if (!fs.existsSync(BLOG_DIR)) {
    console.log('[blog] no content/blog directory — nothing to do');
    return 0;
  }

  const files = fs.readdirSync(BLOG_DIR).filter((f) => f.endsWith('.md'));
  if (!files.length) {
    console.log('[blog] no markdown posts found');
    return 0;
  }

  const posts = [];

  for (const f of files) {
    const raw = fs.readFileSync(path.join(BLOG_DIR, f), 'utf8');
    const { data, body } = parseFrontMatter(raw);
    const fallbackSlug = f.replace(/\.md$/, '');

    if (!data.title) {
      console.log('[blog] skip ' + f + ' (no title in front matter)');
      continue;
    }

    const post = {
      title: String(data.title).trim(),
      slug: String(data.slug || fallbackSlug).trim(),
      date: String(data.date || ''),
      datePretty: prettyDate(data.date) || 'Undated',
      author: String(data.author || 'StageLumen Team'),
      category: String(data.category || 'Article'),
      excerpt: String(data.excerpt || '').trim(),
      tags: Array.isArray(data.tags) ? data.tags : [],
      html: mdToHtml(body),
      url: 'content/blog/' + String(data.slug || fallbackSlug).trim() + '.html',
    };

    posts.push(post);
    fs.writeFileSync(path.join(BLOG_DIR, post.slug + '.html'), articlePage(post));
    console.log('[blog] wrote content/blog/' + post.slug + '.html');
  }

  posts.sort((a, b) => String(b.date).localeCompare(String(a.date)));

  // Index for future JS consumers (search, related posts, sitemap).
  if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(
    path.join(DATA_DIR, 'posts.json'),
    JSON.stringify({
      generated: new Date().toISOString(),
      count: posts.length,
      posts: posts.map((p) => ({
        title: p.title, slug: p.slug, date: p.date, datePretty: p.datePretty,
        category: p.category, excerpt: p.excerpt, tags: p.tags, url: p.url,
      })),
    }, null, 2)
  );
  console.log('[blog] wrote data/posts.json (' + posts.length + ' posts)');

  // news.html card grid
  if (fs.existsSync(NEWS_FILE)) {
    const news = fs.readFileSync(NEWS_FILE, 'utf8');
    const re = /([\t ]*)<!-- POSTS:BEGIN -->[\s\S]*?<!-- POSTS:END -->/;
    if (!re.test(news)) {
      console.log('[blog] news.html has no POSTS markers — left untouched');
    } else {
      // Match the file's own line endings so we do not rewrite every line.
      const nl = news.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
      const out = news.replace(re, (match, indent) => {
        const cards = posts.map((p, i) => cardHtml(p, i, i === 0)).join(nl + nl);
        return [
          '<!-- POSTS:BEGIN -->',
          indent + '<div class="news-grid" id="post-grid">',
          cards,
          indent + '</div>',
          indent + '<!-- POSTS:END -->',
        ].join(nl);
      });
      fs.writeFileSync(NEWS_FILE, out);
      console.log('[blog] injected ' + posts.length + ' card(s) into news.html');
    }
  }

  // sitemap.xml — without this, new articles are invisible to crawlers until
  // they happen to be linked from a page that is already indexed.
  if (fs.existsSync(SITEMAP_FILE)) {
    const sm = fs.readFileSync(SITEMAP_FILE, 'utf8');
    const re = /([\t ]*)<!-- SITEMAP:BEGIN -->[\s\S]*?<!-- SITEMAP:END -->/;
    if (!re.test(sm)) {
      console.log('[blog] sitemap.xml has no SITEMAP markers — left untouched');
    } else {
      const nl = sm.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
      const out = sm.replace(re, (match, indent) => {
        const entries = posts
          .map((p) => {
            const lastmod = String(p.date || '').slice(0, 10);
            const lines = [
              indent + '<url>',
              // Extension-less: Pages 308-redirects .html to this canonical form.
              indent + '  <loc>' + SITE + '/content/blog/' + p.slug + '</loc>',
              indent + '  <changefreq>monthly</changefreq>',
              indent + '  <priority>0.6</priority>',
              indent + '</url>',
            ];
            if (/^\d{4}-\d{2}-\d{2}$/.test(lastmod)) {
              lines.splice(2, 0, indent + '  <lastmod>' + lastmod + '</lastmod>');
            }
            return lines.join(nl);
          })
          .join(nl);
        return ['<!-- SITEMAP:BEGIN -->', entries, indent + '<!-- SITEMAP:END -->'].join(nl);
      });
      fs.writeFileSync(SITEMAP_FILE, out);
      console.log('[blog] injected ' + posts.length + ' article url(s) into sitemap.xml');
    }
  }

  return 0;
}

process.exit(main());
