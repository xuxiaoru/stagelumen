#!/usr/bin/env node
/**
 * Structured data generator (W2).
 *
 * Injects JSON-LD into static HTML:
 *   - Organization + WebSite  -> index.html  (single source of truth for the brand entity)
 *   - FAQPage                 -> every page that has a .faq-item block
 *
 * Run manually (output is committed, Pages build does not call this):
 *   node build/build-jsonld.js          # write
 *   node build/build-jsonld.js --dry    # preview only
 *
 * Design rule (same as inject-settings.js): this must never be able to break
 * the site. Any failure leaves the HTML untouched.
 *
 * Product / Breadcrumb JSON-LD is NOT generated here: product pages are rendered
 * client-side from data/products.json, so it is injected at runtime by the inline
 * script in product-detail.html instead.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'content', 'settings.yml');
const SITE = 'https://www.rigebalighting.com';
const DRY = process.argv.includes('--dry');

/** Only root-level HTML. content/blog/* is regenerated by build-blog.js. */
const SKIP_DIRS = new Set(['node_modules', '.git', '.github', 'functions', 'build', 'admin', 'archive', 'content']);

/** Draft copies that exist locally but are not deployed (verified: /home-v2 is 404 live). */
const SKIP_FILES = new Set(['home-v2.html']);

// Pages that need structured data beyond the FAQ every page can carry. The
// manufacturer page has to define the manufacturer entity itself, and all three
// need breadcrumbs so they are not orphaned in the graph.
const ENTITY_PAGES = {
  'stage-lighting-manufacturer.html': { manufacturer: true, crumb: 'Stage Lighting Manufacturer' },
  'factory.html': { crumb: 'Factory' },
  'stage-lighting.html': { crumb: 'Stage Lighting' },
};

/* ------------------------------------------------------------------ helpers */

function parseFlatYaml(text) {
  const out = {};
  for (const raw of String(text).split(/\r?\n/)) {
    const line = raw.replace(/\s+#.*$/, '');
    if (!line.trim() || /^\s/.test(line)) continue;
    const i = line.indexOf(':');
    if (i < 1) continue;
    const key = line.slice(0, i).trim();
    let val = line.slice(i + 1).trim();
    if (/^".*"$/.test(val) || /^'.*'$/.test(val)) val = val.slice(1, -1);
    if (val) out[key] = val;
  }
  return out;
}

/**
 * Reads one nested block out of settings.yml, e.g.
 *   social:
 *     youtube: "https://www.youtube.com/@rigebalighting"
 *     linkedin: ""
 * Empty values are dropped, so an unfilled block contributes nothing instead of
 * emitting a broken sameAs.
 */
function parseNestedYaml(text, blockKey) {
  const out = {};
  let inside = false;
  for (const raw of String(text).split(/\r?\n/)) {
    const line = raw.replace(/\s+#.*$/, '');
    if (!line.trim()) continue;
    if (!/^\s/.test(line)) {
      inside = line.slice(0, line.indexOf(':')).trim() === blockKey;
      continue;
    }
    if (!inside) continue;
    const i = line.indexOf(':');
    if (i < 1) continue;
    let val = line.slice(i + 1).trim();
    if (/^".*"$/.test(val) || /^'.*'$/.test(val)) val = val.slice(1, -1);
    if (val) out[line.slice(0, i).trim()] = val;
  }
  return out;
}

/** "320+" -> 320. Returns null when the value is not numeric. */
function toCount(v) {
  const n = parseInt(String(v || '').replace(/[^\d]/g, ''), 10);
  return Number.isFinite(n) && n > 0 ? n : null;
}

const ENTITIES = {
  amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ',
  mdash: '\u2014', ndash: '\u2013', hellip: '\u2026', lsquo: '\u2018',
  rsquo: '\u2019', ldquo: '\u201C', rdquo: '\u201D', deg: '\u00B0',
  times: '\u00D7', copy: '\u00A9', reg: '\u00AE', trade: '\u2122',
};
/** Decode HTML entities and strip inline tags -> plain text for JSON-LD. */
function text(html) {
  return String(html)
    .replace(/<[^>]*>/g, '')
    .replace(/&#(\d+);/g, (m, d) => String.fromCharCode(+d))
    .replace(/&#x([0-9a-f]+);/gi, (m, h) => String.fromCharCode(parseInt(h, 16)))
    .replace(/&([a-z]+);/gi, (m, n) => (n.toLowerCase() in ENTITIES ? ENTITIES[n.toLowerCase()] : m))
    .replace(/\s+/g, ' ')
    .trim();
}

const isoCountry = (c) => ({ china: 'CN', 'p.r.china': 'CN', usa: 'US', 'united states': 'US' }[String(c).toLowerCase().trim()] || c);

/** "No. 21, A Rd, B St, Huadu District, Guangzhou, China" -> PostalAddress */
function toAddress(addr) {
  const parts = String(addr || '').split(',').map((s) => s.trim()).filter(Boolean);
  if (!parts.length) return null;
  const country = parts.length > 1 ? parts[parts.length - 1] : '';
  const locality = parts.length > 1 ? parts[parts.length - 2] : parts[0];
  const street = parts.length > 2 ? parts.slice(0, parts.length - 2).join(', ') : parts[0];
  const o = { '@type': 'PostalAddress', streetAddress: street };
  if (parts.length > 1) o.addressLocality = locality;
  if (country) o.addressCountry = isoCountry(country);
  return o;
}

const e164 = (p) => '+' + String(p || '').replace(/[^\d]/g, '');

/** JSON-LD is inside <script>, so a literal "</" would close the tag early. */
function ld(obj) {
  return JSON.stringify(obj, null, 2).replace(/</g, '\\u003c');
}

function collectHtml(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) collectHtml(p, acc);
    else if (e.name.endsWith('.html')) acc.push(p);
  }
  return acc;
}

const pageUrl = (rel) => (rel === 'index.html' ? SITE + '/' : SITE + '/' + rel.replace(/\.html$/, ''));

/** Drop previously injected blocks so re-runs are idempotent. */
function strip(src) {
  return src.replace(/[ \t]*<script type="application\/ld\+json" data-jsonld="[^"]*">[\s\S]*?<\/script>\r?\n?/g, '');
}

function inject(src, blocks) {
  if (!blocks.length) return src;
  const out = strip(src);
  const markup = blocks
    .map((b) => '<script type="application/ld+json" data-jsonld="' + b.id + '">\n' + ld(b.data) + '\n</script>')
    .join('\n');
  if (!out.includes('</head>')) return src;
  return out.replace('</head>', markup + '\n</head>');
}

/* ------------------------------------------------------------- FAQ extractor */

/** Two markup styles exist in this codebase; both are supported. */
function extractFaq(src) {
  const items = [];

  // Style A: <details class="faq-item"><summary>Q</summary><p>A</p></details>
  for (const m of src.matchAll(/<details class="faq-item"[^>]*>([\s\S]*?)<\/details>/g)) {
    const q = m[1].match(/<summary[^>]*>([\s\S]*?)<\/summary>/);
    const a = m[1].match(/<p[^>]*>([\s\S]*?)<\/p>/);
    if (q && a) items.push([text(q[1]), text(a[1])]);
  }

  // Style B: <div class="faq-item"><button class="faq-q">Q</button><div class="faq-a"><p>A</p></div></div>
  if (!items.length) {
    const chunks = src.split('<div class="faq-item">').slice(1);
    for (const c of chunks) {
      const q = c.match(/<button class="faq-q"[^>]*>([\s\S]*?)<\/button>/);
      const a = c.match(/<div class="faq-a"[^>]*>([\s\S]*?)<\/div>/);
      if (q && a) items.push([text(q[1]), text(a[1])]);
    }
  }

  return items
    .filter(([q, a]) => q.length > 8 && a.length > 20)
    .map(([q, a]) => ({
      '@type': 'Question',
      name: q,
      acceptedAnswer: { '@type': 'Answer', text: a },
    }));
}

/* ---------------------------------------------------------------------- main */

function main() {
  let settings;
  let settingsRaw = '';
  try {
    settingsRaw = fs.readFileSync(SRC, 'utf8');
    settings = parseFlatYaml(settingsRaw);
  } catch (e) {
    console.log('[jsonld] settings.yml unreadable — aborting, HTML untouched');
    return 0;
  }

  const brand = settings.brand || 'RiGeBa Lighting';
  const orgId = SITE + '/#organization';

  // knowsAbout comes from the live catalogue so it can never drift from products.json
  let knowsAbout = [];
  try {
    const cats = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'products.json'), 'utf8')).categories || {};
    knowsAbout = Object.values(cats).map((c) => c.label).filter(Boolean);
  } catch (e) { /* optional */ }

  const address = toAddress(settings.address);

  // Entity anchors. Generative engines decide whether a brand is real by looking
  // for the same organisation on domains they already trust. A domain with no
  // sameAs is, to them, an unattributed claim — which is why a page can rank in
  // Google and still never be quoted by ChatGPT.
  const social = parseNestedYaml(settingsRaw, 'social');
  const sameAs = Object.values(social).filter((u) => /^https?:\/\//i.test(u));

  const employees = toCount(settings.teamSize);

  const organization = {
    '@context': 'https://schema.org',
    // Manufacturer is a schema.org Organisation subtype: it tells the parser this
    // is a producer, not a shop, agency or directory.
    '@type': ['Organization', 'Manufacturer'],
    '@id': orgId,
    name: brand,
    legalName: settings.companyLegalName || brand,
    url: SITE + '/',
    ...(settings.tagline ? { slogan: settings.tagline } : {}),
    // Google and Bing use `logo` as the brand mark in knowledge panels and
    // entity cards; `image` is the generic fallback. Both must be absolute.
    logo: {
      '@type': 'ImageObject',
      url: SITE + '/assets/images/brand/logo-rigeba.png',
      width: 182,
      height: 170,
    },
    image: SITE + '/assets/images/brand/og-image.jpg',
    description:
      'Professional stage lighting manufacturer in Guangzhou, China. Moving heads, pixel and effect fixtures, ' +
      'LED PAR and wall washers, lasers, controllers and theatre lighting, supplied factory-direct with OEM / ODM service.',
    ...(settings.founded ? { foundingDate: String(settings.founded).replace(/\D/g, '').slice(0, 4) } : {}),
    ...(address ? { address } : {}),
    ...(settings.email ? { email: settings.email } : {}),
    ...(settings.phone ? { telephone: e164(settings.phone) } : {}),
    ...(knowsAbout.length ? { knowsAbout } : {}),
    ...(sameAs.length ? { sameAs } : {}),
    ...(employees ? { numberOfEmployees: { '@type': 'QuantitativeValue', value: employees } } : {}),
    ...(settings.founded
      ? {
          foundingLocation: {
            '@type': 'Place',
            address: { '@type': 'PostalAddress', addressLocality: 'Guangzhou', addressCountry: 'CN' },
          },
        }
      : {}),
    areaServed: { '@type': 'Place', name: 'Worldwide' },
    knowsLanguage: ['en', 'zh'],
    contactPoint: [
      {
        '@type': 'ContactPoint',
        contactType: 'sales',
        ...(settings.salesRep ? { name: settings.salesRep } : {}),
        ...(settings.email ? { email: settings.email } : {}),
        ...(settings.phone ? { telephone: e164(settings.phone) } : {}),
        availableLanguage: ['English', 'Chinese'],
        areaServed: 'Worldwide',
      },
    ],
  };

  const website = {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    '@id': SITE + '/#website',
    url: SITE + '/',
    name: brand,
    ...(settings.tagline ? { alternateName: settings.tagline } : {}),
    publisher: { '@id': orgId },
    inLanguage: 'en',
  };

  let files = 0;
  for (const file of collectHtml(ROOT)) {
    const rel = path.relative(ROOT, file);
    if (SKIP_FILES.has(rel)) continue;
    const src = fs.readFileSync(file, 'utf8');
    const blocks = [];

    if (rel === 'index.html') {
      blocks.push({ id: 'organization', data: organization });
      blocks.push({ id: 'website', data: website });
    }

    const extra = ENTITY_PAGES[rel];
    if (extra && extra.manufacturer) {
      // Same object as the homepage, re-anchored to this page: the page that
      // targets "stage lighting manufacturer" should be the page that defines
      // the manufacturer, not a page that merely mentions it.
      blocks.push({ id: 'manufacturer', data: { ...organization, '@id': pageUrl(rel), mainEntityOfPage: { '@id': orgId } } });
    }
    if (extra && extra.crumb) {
      blocks.push({
        id: 'breadcrumb',
        data: {
          '@context': 'https://schema.org',
          '@type': 'BreadcrumbList',
          itemListElement: [
            { '@type': 'ListItem', position: 1, name: 'Home', item: SITE + '/' },
            { '@type': 'ListItem', position: 2, name: extra.crumb, item: pageUrl(rel) },
          ],
        },
      });
    }

    const faq = extractFaq(src);
    if (faq.length) {
      blocks.push({
        id: 'faq',
        data: {
          '@context': 'https://schema.org',
          '@type': 'FAQPage',
          '@id': pageUrl(rel) + '#faq',
          url: pageUrl(rel),
          mainEntity: faq,
        },
      });
    }

    if (!blocks.length) continue;

    const out = inject(src, blocks);
    if (out === src) {
      console.log('  skip   ' + rel + ' (no </head> or nothing to do)');
      continue;
    }

    const kinds = blocks.map((b) => b.id + (b.id === 'faq' ? '(' + faq.length + ')' : '')).join(' + ');
    console.log('  write  ' + rel + '  ->  ' + kinds);
    if (!DRY) fs.writeFileSync(file, out);
    files++;
  }

  console.log('[jsonld] ' + (DRY ? 'DRY RUN — would update ' : 'updated ') + files + ' file(s)');
  return 0;
}

process.exit(main());
