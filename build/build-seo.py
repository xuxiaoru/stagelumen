#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Day-1 SEO 资产生成器（可重复运行）。

产出（写到仓库根）：
  robots.txt              正式域名 Sitemap + 显式放行 AI 爬虫
  sitemap.xml             静态页 + 7 个分类页 + 全部博客（真实可达、有实质内容的 URL）
  sitemap-products.xml    361 个产品 URL（**默认不写进 robots.txt**，等 W3-4 产品页静态化后再合并）
  llms.txt                GEO 品牌档案：公司事实 / 各品类 / 代表型号 / 买家问答

用法：
  python build/build-seo.py                 # 常规
  python build/build-seo.py --with-products # 产品 URL 也并入主 sitemap（静态化完成后再用）

注意：
  - sitemap.xml 保留 <!-- SITEMAP:BEGIN/END --> 标记，Pages 构建时 build-blog.js
    会重写其中的博客段；两者都读 data/posts.json 且都用同一个 SITE，结果一致。
  - URL 一律用「无扩展名 pretty 形式」：线上 /x.html 会 308 到 /x。
"""
import json, os, sys, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://www.rigebalighting.com"
TODAY = datetime.date.today().isoformat()

STATIC_PAGES = [
    ("/",               "weekly",  "1.0"),
    ("/products",       "daily",   "0.9"),
    ("/solutions",      "weekly",  "0.85"),
    ("/oem-odm",        "monthly", "0.8"),
    ("/rfq",            "monthly", "0.8"),
    ("/about",          "monthly", "0.7"),
    ("/contact",        "monthly", "0.7"),
    ("/projects",       "monthly", "0.7"),
    ("/support",        "monthly", "0.7"),
    ("/resources",      "monthly", "0.6"),
    ("/news",           "weekly",  "0.6"),
    ("/privacy",        "yearly",  "0.3"),
    ("/terms",          "yearly",  "0.3"),
    ("/cookies",        "yearly",  "0.3"),
]

CATS = ["moving", "pixel", "theatre", "par", "laser", "controller", "profile",
        "effect", "kinetic"]

AI_BOTS = [
    ("GPTBot",              "OpenAI"),
    ("OAI-SearchBot",       "OpenAI search"),
    ("ChatGPT-User",        "ChatGPT on-demand"),
    ("PerplexityBot",       "Perplexity"),
    ("ClaudeBot",           "Anthropic"),
    ("anthropic-ai",        "Anthropic"),
    ("Claude-Web",          "Anthropic"),
    ("Google-Extended",     "Google Gemini grounding"),
    ("Applebot",            "Apple"),
    ("Applebot-Extended",   "Apple Intelligence"),
    ("CCBot",               "Common Crawl"),
    ("Amazonbot",           "Amazon"),
    ("Diffbot",             "Diffbot"),
    ("Bytespider",          "ByteDance"),
]


def load(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return json.load(f)


def write(rel, text):
    p = os.path.join(ROOT, rel)
    nl = "\r\n" if os.path.exists(p) and "\r\n" in open(p, encoding="utf-8", newline="").read() else "\n"
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(text.replace("\n", nl) if nl == "\r\n" else text)
    print("  wrote %-24s %5d bytes" % (rel, len(text)))


def url_block(loc, lastmod, changefreq, priority, indent="  "):
    return (
        "%s<url>\n%s  <loc>%s</loc>\n%s  <lastmod>%s</lastmod>\n"
        "%s  <changefreq>%s</changefreq>\n%s  <priority>%s</priority>\n%s</url>"
        % (indent, indent, loc, indent, lastmod, indent, changefreq, indent, priority, indent)
    )


def main():
    with_products = "--with-products" in sys.argv
    prods = load("products.json")
    posts_doc = load("posts.json")
    posts = posts_doc.get("posts", [])
    cats = prods.get("categories", {})
    products = prods["products"]

    # ---------------- robots.txt ----------------
    r = ["# RiGeBa Lighting — robots.txt",
         "# Generated by build/build-seo.py (%s)" % TODAY,
         "",
         "User-agent: *",
         "Allow: /",
         "Disallow: /admin/",
         "Disallow: /api/",
         ""]
    for bot, note in AI_BOTS:
        r += ["# %s (%s) — explicitly allowed" % (bot, note),
              "User-agent: %s" % bot,
              "Allow: /",
              ""]
    r += ["Sitemap: %s/sitemap.xml" % SITE,
          "Sitemap: %s/sitemap-products.xml" % SITE if with_products else "# Sitemap: %s/sitemap-products.xml  (enable after product pages are prerendered)" % SITE,
          ""]
    write("robots.txt", "\n".join(r))

    # ---------------- sitemap.xml ----------------
    head = ['<?xml version="1.0" encoding="UTF-8"?>',
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    body = [url_block(SITE + path, TODAY, cf, pr) for path, cf, pr in STATIC_PAGES]
    for c in CATS:
        body.append(url_block("%s/products?cat=%s" % (SITE, c), TODAY, "weekly", "0.8"))
    body.append("  <!-- WARNING: do not index the Cloudflare preview host stagelumen.pages.dev -->")
    blog_entries = []
    for p in posts:
        slug = p["slug"]
        d = (p.get("date") or TODAY)[:10]
        blog_entries.append(url_block("%s/content/blog/%s" % (SITE, slug), d, "monthly", "0.6"))
    if with_products:
        for prod in products:
            body.append(url_block("%s/products/%s/%s" % (SITE, prod["category"], prod["id"]), TODAY, "weekly", "0.7"))
    tail = ["</urlset>", ""]
    xml = "\n".join(
        head + body
        + ["  <!-- SITEMAP:BEGIN -->"] + blog_entries + ["  <!-- SITEMAP:END -->"]
        + tail
    )
    write("sitemap.xml", xml)

    # ---------------- sitemap-products.xml（待启用） ----------------
    pentry = [url_block("%s/products/%s/%s" % (SITE, p["category"], p["id"]), TODAY, "weekly", "0.7")
              for p in products]
    write("sitemap-products.xml",
          "\n".join(['<?xml version="1.0" encoding="UTF-8"?>',
                     '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
                    + pentry + ["</urlset>", ""]))

    # ---------------- llms.txt ----------------
    def num(v, default=0):
        try:
            return float(str(v).replace(",", "").strip())
        except Exception:
            return float(default)

    def pick(cat, n=4):
        pool = [p for p in products if p["category"] == cat]
        pool.sort(key=lambda x: (0 if x.get("hero") else 1,
                                 -num(x.get("priority")),
                                 -num(x.get("price"))))
        return pool[:n]

    L = []
    L += ["# RiGeBa Lighting",
          "> Guangzhou manufacturer of professional LED stage lighting: moving heads, pixel and effect",
          "> fixtures, outdoor IP65 units, LED PAR and uplights, profile spots, lasers and DMX control.",
          "> %d models in catalogue, factory-direct EXW pricing, OEM / ODM for rental houses," % len(products),
          "> distributors, integrators and venues.",
          "",
          "## Company facts",
          "- Legal entity: GuangZhou GeLiang Lighting Technology Co.,Ltd (trading as RiGeBa Lighting)",
          "- Location: No. 21, Lingdong Road, Xiuquan Street, Huadu District, Guangzhou, China",
          "- Manufacturing since 2010; own factory ~8,000 m2 with 320+ engineers, assemblers and QC staff",
          "- In-house SMT line and aging test before packing",
          "- Certifications: ISO 9001:2015, CE, RoHS (FCC / UL / RCM / PSE on request for qualified orders)",
          "- Buyers in 60+ countries",
          "- Trade terms: EXW Guangzhou by default; FOB, CIF and DDP available; payment by T/T",
          "- No minimum order quantity on catalogue models; OEM tooling typically 100-300 units per model",
          "- OEM / ODM: housing, housing colour, logo print, product naming, carton artwork, manuals, firmware behaviour",
          "- Sample units available at single-unit price plus freight, shipped with aging-test result and packing photos",
          "- Production lead time: 7-15 days for stock models, 25-35 days for volume orders",
          "- Quote turnaround: within 24 hours",
          "- Warranty: limited warranty against manufacturing defects; exact coverage is stated on the order confirmation. Spare parts (boards, drivers, lamps, bearings) are stocked in Guangzhou.",
          "",
          "## Contact",
          "- Website: %s" % SITE,
          "- Export sales: Vivian",
          "- E-mail: sales20@rigelighting.com",
          "- Mobile / WhatsApp / WeChat: +86 134 3026 2182",
          "",
          "## Catalogue — %d models in 7 ranges" % len(products)]
    for c in CATS:
        meta = cats.get(c, {})
        n = len([p for p in products if p["category"] == c])
        L.append("")
        L.append("### %s — %d models (%s)" % (meta.get("label", c), n, meta.get("desc", c)))
        L.append("- Category page: %s/products?cat=%s" % (SITE, c))
        for p in pick(c):
            desc = (p.get("tagline") or p.get("shortDesc") or "").strip().replace("\n", " ")
            if len(desc) > 96:
                desc = desc[:93].rsplit(" ", 1)[0] + "..."
            price = p.get("price")
            inc = p.get("incoterm") or "EXW"
            tail_ = " — %s from US$%s" % (inc, f"{price:,.0f}") if price else ""
            L.append("- %s — %s%s — %s/products/%s/%s" % (p["model"], desc, tail_, SITE, p["category"], p["id"]))

    kb = load("kb.json")
    entries = kb.get("entries", [])
    wanted = ["kb-lead-time", "kb-process", "kb-samples"]  # 其余按 tags 命中补
    chosen = [e for e in entries if e["id"] in wanted]
    for e in entries:
        tags = " ".join(e.get("tags", []))
        if e["id"] in wanted:
            continue
        if any(k in tags for k in ("oem", "moq", "certif", "payment", "shipping", "warranty", "qc", "custom")):
            chosen.append(e)
    L += ["", "## Buyer questions", ""]
    for e in chosen[:10]:
        L.append("Q: %s" % e["q"].strip())
        L.append("A: %s" % " ".join(e["a"].split()))
        L.append("")

    L += ["## Key pages",
          "- Home: %s/" % SITE,
          "- All %d models: %s/products" % (len(products), SITE)]
    for c in CATS:
        L.append("- %s: %s/products?cat=%s" % (cats.get(c, {}).get("label", c), SITE, c))
    L += ["- Request a quote (RFQ): %s/rfq" % SITE,
          "- OEM / ODM service: %s/oem-odm" % SITE,
          "- Solutions by venue: %s/solutions" % SITE,
          "- About the factory: %s/about" % SITE,
          "- Support, downloads and DMX files: %s/support" % SITE,
          "- Blog / buyer guides: %s/news" % SITE,
          ""]
    write("llms.txt", "\n".join(L))

    print("\nURL 统计：静态 %d + 分类 %d + 博客 %d 篇 = %d 条进入主 sitemap（产品 %d 条待静态化后再并入）"
          % (len(STATIC_PAGES), len(CATS), len(posts), len(STATIC_PAGES) + len(CATS) + len(posts), len(products)))


if __name__ == "__main__":
    main()
